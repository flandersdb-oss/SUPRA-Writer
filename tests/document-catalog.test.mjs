import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const catalog=require('../desktop/document-catalog.cjs');
test('Universal discovery enumerates readable and conversion-needed documents without reading content',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'supra-catalog-test-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const docs=path.join(root,'Documents');
 await fs.mkdir(docs);
 await fs.writeFile(path.join(docs,'letter.docx'),'test DOCX');
 await fs.writeFile(path.join(docs,'note.md'),'# a note');
 await fs.writeFile(path.join(docs,'page.htm'),'<p>hi</p>');
 await fs.writeFile(path.join(docs,'old.doc'),'binary-old');
 await fs.writeFile(path.join(docs,'ignored.jpg'),'not a document');
 await fs.mkdir(path.join(docs,'.hidden'));
 await fs.writeFile(path.join(docs,'.hidden','private.txt'),'private');
 await fs.mkdir(path.join(docs,'nested'));
 await fs.writeFile(path.join(docs,'nested','report.odt'),'odt');
 const outside=path.join(root,'Outside');
 await fs.mkdir(outside);
 await fs.writeFile(path.join(outside,'secret.txt'),'secret');
 try{await fs.symlink(outside,path.join(docs,'linked'),'dir');}catch{}
 const result=await catalog.scanRoots([docs]);
 const files=result.items.map(x=>x.item.name).sort();
 assert.deepEqual(files,['letter.docx','note.md','old.doc','page.htm','report.odt']);
 assert.equal(result.items.length,5);
 assert.equal(result.items.filter(x=>x.item.canOpen).length,3);
 assert.ok(result.items.every(x=>!Object.hasOwn(x.item,'path')),'renderer metadata excludes absolute filesystem paths');
 assert.equal(result.items.find(x=>x.item.name==='old.doc').item.kind,'converter-needed');
 assert.equal(result.items.find(x=>x.item.name==='old.doc').item.adapter,'libreoffice');
 assert.equal(result.items.find(x=>x.item.name==='report.odt').item.adapter,'libreoffice');
 assert.equal(catalog.adapterFor('.tex'),'pandoc');
 assert.equal(catalog.adapterFor('.docm'),null);
 assert.equal(result.items.find(x=>x.item.name==='page.htm').item.kind,'readable');
 const open=await catalog.verifyIndexedFile(result.items.find(x=>x.item.name==='letter.docx'));
 assert.equal(open,path.join(docs,'letter.docx'));
 await assert.rejects(()=>catalog.verifyIndexedFile(result.items.find(x=>x.item.name==='old.doc')),/converter/i);
 assert.equal((await catalog.scanRoots([docs],{maxDepth:0})).items.length,4,'depth zero excludes nested directories');
 const small=await catalog.scanRoots([docs],{maxItems:2});
 assert.equal(small.items.length,2);assert.equal(small.truncated,true);
});
test('Catalog enforces limits, refuses traversal and does not accept arbitrary paths',async()=>{
 assert.equal(catalog.classify('notes.MD').kind,'readable');
 assert.equal(catalog.classify('test.exe').kind,null);
 assert.equal(catalog.inside('/tmp/folder','/tmp/folder2/file.txt'),false);
 await assert.rejects(()=>catalog.scanRoots(Array(11).fill('/tmp')),/at most ten/);
 await assert.rejects(()=>catalog.verifyIndexedFile({path:'../unknown'}),/Unknown indexed file/);
});
test('Windows desktop exposes consent-scoped API and never installs converters silently',async()=>{
 const src=await fs.readFile(new URL('../desktop/main.cjs',import.meta.url),'utf8');
 const preload=await fs.readFile(new URL('../desktop/preload.cjs',import.meta.url),'utf8');
 const renderer=await fs.readFile(new URL('../office/writer-discovery.js',import.meta.url),'utf8');
 for(const name of ['catalog:choose','catalog:scan','catalog:open','catalog:forget'])assert.ok(src.includes(name));
 assert.match(src,/showOpenDialog/);
 assert.match(src,/readCatalogConfig/);
 assert.match(src,/verifyIndexedFile/);
 assert.match(preload,/catalogChoose/);
 assert.match(preload,/catalogForget/);
 assert.match(preload,/catalogAdapterSource/);
 assert.match(src,/catalog:adapter-source/);
 assert.match(src,/www\.libreoffice\.org/);
 assert.match(src,/pandoc\.org/);
 assert.match(renderer,/first-launch|intro|read-only/i);
 assert.doesNotMatch(renderer,/child_process|eval\(|fetch\(/i);
});
